//! # High-Level Database Interface

const std = @import("std");
const log = std.log;
const mem = std.mem;
const debug = std.debug;
const ArrayList = std.ArrayList;
const Allocator = mem.Allocator;

const jsonic = @import("jsonic");

const types = @import("./types.zig");

const sqlite3 = @import("../binding/sqlite3.zig");
const STMT = sqlite3.STMT;
const Flag = sqlite3.OpenFlag;
const Option = sqlite3.Option;
const Database = sqlite3.Database;
const ExecResult = sqlite3.ExecResult;

pub const Result = sqlite3.Result;


heap: Allocator,
instance: sqlite3.Database,

const Self = @This();

/// # Initializes SQLite with Global Configuration
pub fn init(opt: Option) !void {
    try sqlite3.config(@intFromEnum(opt));
    try sqlite3.initialize();
}

/// # Destroys SQLite Resources and Configurations
pub fn deinit() void {
    sqlite3.shutdown() catch |err| { log.err("{s}", .{@errorName(err)}); };
}

/// # Open or Creates a Database Instance
/// - `filename` - When **null**, creates an in-memory database
pub fn open(heap: Allocator, filename: ?[]const u8) !Self {
    const flags = @intFromEnum(Flag.Create) | @intFromEnum(Flag.WriteWrite);

    const db = if (filename) |file| try sqlite3.openV2(file, flags)
    else try sqlite3.openV2(":memory:", flags);

    return .{.heap = heap, .instance = db};
}

/// # Closes the Database Instance
pub fn close(self: *Self) void { sqlite3.closeV2(self.instance); }

/// # Performs One-Step Query Execution
/// - Convenient wrapper around `prepare()`, `step()`, and `finalize()`
/// - Use only for non-repetitive SQL statements such as creating a table
/// - Avoid when parameter binding or retrieving complex results is required
///
/// **Remarks:**
/// - The callback function receives the results one row at a time
/// - All row data retrieve by the `exec()` is in text representation
/// - In a multiple statement execution, `exec()` does not explicitly tell the
///   callback which statement produced a particular row.
pub fn exec(self: *Self, sql: []const u8) !ExecResult {
    return try sqlite3.exec(self.heap, self.instance, sql);
}

/// # Compiles SQL Text into Byte-Code
/// **Remarks:** Generated Byte-Code get cached for identical statements.
pub fn prepare(self: *Self, sql: []const u8) !CRUD {
    const stmt = sqlite3.prepareV3(self.instance, sql) catch |err| {
        log.warn("{s}", .{self.errMsg()});
        return err;
    };
    return CRUD.create(self, stmt);
}

/// # Shows Human-Readable Error Message
/// - Most recent error that occurred on a given database connection
pub fn errMsg(self: *Self) []const u8 {
    return sqlite3.errMsg(self.instance);
}

/// # Provides Database Interactions
/// - Supports single statement query (first one)
/// - In a multi-statement query, other statements are discarded
///
/// **WARNING:** You must call `destroy()` at the end to release the STMT
pub const CRUD = struct {
    db: *Self,
    stmt: STMT,

    /// # Creates the Interface
    /// - **Remarks:** For internal use only, by the `Self.prepare()`
    fn create(db: *Self, stmt: STMT) CRUD {
        return .{.db = db, .stmt = stmt };
    }

    /// # Destroys the Interface
    pub fn destroy(self: *CRUD) void {
        sqlite3.finalize(self.stmt) catch |err| {
            log.err("{s}", .{@errorName(err)});
        };
    }

    /// # Frees Up Heap Allocated Memories
    /// - Retrieved by read operations - `readOne()` and `readMany()`
    pub fn free(self: *CRUD, result: anytype) void {
        const T = @TypeOf(result);
        switch (@typeInfo(T)) {
            .@"struct" => {
                release(self.db.heap, result);
            },
            .optional => {
                if (result == null) return;
                release(self.db.heap, result.?);
            },
            .pointer => |p| {
                if (!(p.is_const and p.size == .slice)) {
                    @compileError("quill: Pointer type must be `[]const T`");
                }

                const items: T = result;
                for (0..items.len) |i| release(self.db.heap, items[i]);
                self.db.heap.free(items);
            },
            else => @compileError(
                "quill: Result must be a struct of - `T`, `?T` or `[]const T`"
            )
        }
    }

    fn release(heap: Allocator, data: anytype) void {
        const info = @typeInfo(@TypeOf(data)).@"struct";
        const err_str = "quill: Pointer type must be `[]const T`";

        inline for (info.fields) |field| {
            const value = @field(data, field.name);
            switch (@typeInfo(field.type)) {
                .@"struct" => try jsonic.free(heap, value),
                .optional => |o| {
                    switch(@typeInfo(o.child)) {
                        .@"struct" => if (value) |v| try jsonic.free(heap, v),
                        .pointer => |p| {
                            if (!(p.is_const and p.size == .slice)) {
                                @compileError(err_str);
                            }

                            if (p.child == u8) { if (value) |v| heap.free(v); }
                            else { if (value) |v| try jsonic.free(heap, v); }
                        },
                        else => {} // NOP
                    }
                },
                .pointer => |p| {
                    if (!(p.is_const and p.size == .slice)) {
                        @compileError(err_str);
                    }

                    if (p.child == u8) heap.free(value)
                    else try jsonic.free(heap, value);
                },
                else => {} // NOP
            }
        }
    }

    /// # Retrieves a Single (Record) Query Result
    /// **Remarks:** For multiple records only the first one is retrieved
    /// - `T` - Record View structure
    /// - `filter` - **null**, Otherwise instance of an Filter structure
    ///
    /// **WARNING:** Result must be freed by calling `free()`
    pub fn readOne(self: *CRUD, comptime T: type, filter: anytype) !?T {
        if (@TypeOf(filter) != @TypeOf(null)) {
            var params = sqlite3.Bind.init(self.db.heap, self.stmt);
            try types.bindFilterData(&params, filter);
        }

        if (try sqlite3.step(self.stmt) == .Done) return null;

        var column = sqlite3.Column.init(self.db.heap, self.stmt);
        return try types.convertTo(self.db.heap, &column, T);
    }

    /// # Retrieves Multiple (Records) Query Result
    /// **Remarks:** Use this when record limits are known. Otherwise use
    /// the `readOne()` within a while loop for progressive retrieval.
    /// - `T` - Record View structure
    /// - `filter` - **null**, Otherwise instance of an Filter structure
    ///
    /// **WARNING:** Result must be freed by calling `free()`
    pub fn readMany(self: *CRUD, comptime T: type, filter: anytype) ![]const T {
        if (@TypeOf(filter) != @TypeOf(null)) {
            var params = sqlite3.Bind.init(self.db.heap, self.stmt);
            try types.bindFilterData(&params, filter);
        }

        var records = ArrayList(T).init(self.db.heap);
        while (try sqlite3.step(self.stmt) == .Row) {
            var column = sqlite3.Column.init(self.db.heap, self.stmt);
            try records.append(try types.convertTo(self.db.heap, &column, T));
        }

        return try records.toOwnedSlice();
    }

    /// # Returns Total Number of Matching Records
    /// **Remarks:** When filter is `null` total record count is returned
    /// - `filter` - **null**, Otherwise instance of an Filter structure
    pub fn count(self: *CRUD, filter: anytype) !usize {
        if (@TypeOf(filter) != @TypeOf(null)) {
            var params = sqlite3.Bind.init(self.db.heap, self.stmt);
            try types.bindFilterData(&params, filter);
        }

        debug.assert(try sqlite3.step(self.stmt) == .Row);
        const column = sqlite3.Column.init(self.db.heap, self.stmt);

        debug.assert(column.dataType(0) == .Int);
        return @intCast(column.int64(0));
    }

    const ExecCallback = *const fn(result: Result, affected: i64) void;

    /// # Binds Params Data and then Executes a SQL Statement
    /// **Remarks:** Can be used for both creating and updating records
    ///
    /// `callback` - Captures execution result when not **NULL**
    pub fn exec(
        self: *CRUD,
        record: anytype,
        filter: anytype,
        callback: ?ExecCallback
    ) !void {
        if (@TypeOf(filter) != @TypeOf(null)) {
            var params = sqlite3.Bind.init(self.db.heap, self.stmt);
            try types.bindFilterData(&params, filter);
        }

        var list = ArrayList([]const u8).init(self.db.heap);
        defer {
            for (list.items) |item| self.db.heap.free(item);
            list.deinit();
        }

        var params = sqlite3.Bind.init(self.db.heap, self.stmt);
        try types.convertFrom(self.db.heap, &list, &params, record);

        const result = try sqlite3.step(self.stmt);
        const affected = sqlite3.changes64(self.db.instance);
        if (callback) |cb| cb(result, affected);
    }

    /// # Removes Matching Records from the Container
    /// **Remarks:** When filter is `null` all record is removed.
    /// Use `builtins.Container.clear()` instead for vacuuming unused space.
    /// - `filter` - **null**, Otherwise instance of an Filter structure
    ///
    /// `callback` - Captures remove result when not **NULL**
    pub fn remove(self: *CRUD, filter: anytype, callback: ?ExecCallback) !void {
        if (@TypeOf(filter) != @TypeOf(null)) {
            var params = sqlite3.Bind.init(self.db.heap, self.stmt);
            try types.bindFilterData(&params, filter);
        }

        const result = try sqlite3.step(self.stmt);
        const affected = sqlite3.changes64(self.db.instance);
        if (callback) |cb| cb(result, affected);
    }
};

pub const AcidSession = struct {
    const Action = enum { Commit, Rollback };
    const Callback = *const fn(result: ExecResult) void;

    /// # Starts ACID Session for Multiple Transaction
    /// - `callback` - Captures execution result when not **NULL**
    pub fn start(self: *Self, callback: ?Callback) !void {
        var result = try self.exec("BEGIN TRANSACTION;");
        if (callback) |cb| cb(result)
        else result.destroy();
    }

    /// # Ends ACID Session for Multiple Transaction
    /// - `callback` - Captures execution result when not **NULL**
    pub fn end(self: *Self, act: Action, callback: ?Callback) !void {
        var result = switch (act) {
            .Commit => try self.exec("COMMIT;"),
            .Rollback => try self.exec("ROLLBACK;")
        };

        if (callback) |cb| cb(result)
        else result.destroy();
    }
};

